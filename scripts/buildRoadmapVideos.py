#!/usr/bin/env python3
"""Regenerate src/data/roadmapVideos.ts from JustinGuitar's official course playlists.

The roadmap links Justin Sandercoe's free YouTube guitar course into each bullet
point. This script pulls his seven official per-grade course playlists (in course
order), concatenates + de-duplicates them (first occurrence wins, so a video that
Justin reuses in a later grade keeps its earliest slot), assigns a GLOBAL
chronological number `n`, and groups each video under a roadmap target.

Targets come from scripts/roadmapVideoMap.json — a curated { videoId: target } map
where target is a roadmap item id (e.g. "l1-open-chords") or a bare level id
("l1".."l8") for videos that fit the level but no single bullet. Videos NOT in the
map (i.e. new lessons Justin has added since the map was last curated) fall back to
their grade's level id and are printed as a warning so you can curate them later.

Usage:  pip install yt-dlp  &&  python3 scripts/buildRoadmapVideos.py
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, 'src', 'data', 'roadmapVideos.ts')
MAP = os.path.join(HERE, 'roadmapVideoMap.json')

# Justin's official master course playlists, in path order. grade -> playlist id.
# Grades 1-3 = Beginner (roadmap l1-l3), 4-6 = Intermediate (l4-l6), 7 = Advanced (l7).
PLAYLISTS = {
    1: 'PLlwfspJqZ126JHOY5rTkKCSAp2Ua907-v',
    2: 'PLlwfspJqZ127Mf3ilux771YB9BYgEu917',
    3: 'PLlwfspJqZ1276gxdqEuNrEPTj80rMY9ls',
    4: 'PLlwfspJqZ127S23d-gTEKCxHQ1l6x6rVE',
    5: 'PLlwfspJqZ125N-Yv8HS3krL69lcm0Ar1b',
    6: 'PLlwfspJqZ127-HOkePXuJM_CQuUfbaAqq',
    7: 'PLlwfspJqZ1268vqZx7IVpGKYaxZRxQqR4',
}
# Fallback level id for a grade's videos that aren't in the curated map.
GRADE_LEVEL = {1: 'l1', 2: 'l2', 3: 'l3', 4: 'l4', 5: 'l5', 6: 'l6', 7: 'l7'}


def pull(playlist_id):
    """Return [(videoId, title), ...] in playlist order, dropping dead (private/deleted) entries."""
    url = f'https://www.youtube.com/playlist?list={playlist_id}'
    out = subprocess.run(
        ['yt-dlp', '--flat-playlist', '--print', '%(id)s\t%(title)s', url],
        capture_output=True, text=True, check=True,
    ).stdout
    rows = []
    for line in out.splitlines():
        if not line.strip():
            continue
        vid, title = line.split('\t', 1)
        if title == 'NA':  # yt-dlp prints NA for unavailable videos
            continue
        rows.append((vid, title))
    return rows


def esc(s):
    return s.replace('\\', '\\\\').replace("'", "\\'")


def main():
    curated = json.load(open(MAP))
    seen = set()
    videos = []          # (n, grade, vid, title, target)
    unmapped = []
    n = 0
    for grade in sorted(PLAYLISTS):
        print(f'Pulling Grade {grade}...', file=sys.stderr)
        for vid, title in pull(PLAYLISTS[grade]):
            if vid in seen:
                continue
            seen.add(vid)
            n += 1
            target = curated.get(vid)
            if target is None:
                target = GRADE_LEVEL[grade]
                unmapped.append((n, grade, vid, title))
            videos.append((n, grade, vid, title, target))

    # Group by target, preserving first-seen order of targets.
    order, groups = [], {}
    for n, grade, vid, title, target in videos:
        if target not in groups:
            groups[target] = []
            order.append(target)
        groups[target].append((n, vid, title))

    lines = [
        '// AUTO-GENERATED by scripts/buildRoadmapVideos.py — do not edit by hand.',
        "// JustinGuitar's official per-grade YouTube course playlists (Grades 1-7),",
        '// concatenated in course order and de-duplicated. `n` is the global',
        '// chronological position across the whole series; `id` is the YouTube video',
        '// id (also the localStorage key for the watched checkmark). Keys are roadmap',
        '// item ids, or a bare level id (l1..l8) for videos that fit the level but no',
        '// single bullet point.',
        'export type RoadmapVideo = { n: number; id: string; title: string };',
        '',
        'export const ROADMAP_VIDEOS: Record<string, RoadmapVideo[]> = {',
    ]
    for t in order:
        lines.append(f"  '{t}': [")
        for n, vid, title in groups[t]:
            lines.append(f"    {{ n: {n}, id: '{vid}', title: '{esc(title)}' }},")
        lines.append('  ],')
    lines.append('};')
    lines.append('')
    lines.append('export const youtubeUrl = (id: string) => `https://www.youtube.com/watch?v=${id}`;')
    lines.append('')
    lines.append(f'export const TOTAL_ROADMAP_VIDEOS = {len(videos)};')
    lines.append('')
    open(OUT, 'w').write('\n'.join(lines))

    print(f'Wrote {OUT}: {len(videos)} videos, {len(groups)} groups.', file=sys.stderr)
    if unmapped:
        print(f'\n{len(unmapped)} video(s) not in roadmapVideoMap.json (defaulted to level '
              'fallback — add them to the map to place them on a specific bullet):', file=sys.stderr)
        for n, grade, vid, title in unmapped:
            print(f'  #{n} [G{grade}] {vid}  {title}', file=sys.stderr)


if __name__ == '__main__':
    main()
