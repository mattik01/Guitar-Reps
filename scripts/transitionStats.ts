// Global chord-transition statistics over the built catalog: how often each
// undirected base-triad pair occurs, and how fast the songs it lives in actually
// run. This is the evidence behind src/data/transitionTargets.ts.
//
// Run: npm run stats:transitions   (~90 s over 376k songs)
//
// Output:
//   • data/raw/transition-stats.csv    — a,b,songs,occurrences,avgBpm,avgGreen
//   • src/data/transitionFrequency.ts  — the same ranking, generated for the app
//   • the top 120 printed to stdout
//
// "green" is the app's own definition of fast enough for a song —
// speedAnchors(tempo).green = min(bpm/2, 120) swaps/min — averaged over every
// occurrence of the pair. Spoiler, and the reason the curriculum doesn't use a
// per-pair tempo: it comes out at 59.8–63.2 for every one of the top 120.
import fs from 'node:fs';
import Database from 'better-sqlite3';
import { computeSongTransitions, speedAnchors } from '../src/data/songTransitions';

const DB = 'public/catalog.sqlite';
const OUT = 'data/raw/transition-stats.csv';
const GENERATED = 'src/data/transitionFrequency.ts';

const db = new Database(DB, { readonly: true });
const rows = db.prepare(
  `SELECT tempo, progression FROM songs
    WHERE tempo IS NOT NULL AND tempo > 0 AND progression IS NOT NULL AND progression <> ''`,
).iterate() as Iterable<{ tempo: number; progression: string }>;

type Agg = { songs: number; occ: number; greenSum: number; bpmSum: number };
const agg = new Map<string, Agg>();
let scanned = 0;

for (const r of rows) {
  scanned++;
  const green = speedAnchors(r.tempo).green;
  for (const t of computeSongTransitions(r.progression)) {
    const k = `${t.a}\t${t.b}`;
    let e = agg.get(k);
    if (!e) agg.set(k, (e = { songs: 0, occ: 0, greenSum: 0, bpmSum: 0 }));
    e.songs++;
    e.occ += t.count;
    e.greenSum += green * t.count;
    e.bpmSum += r.tempo * t.count;
  }
}

const ranked = [...agg.entries()]
  .map(([k, e]) => {
    const [a, b] = k.split('\t');
    return { a, b, songs: e.songs, occ: e.occ, bpm: e.bpmSum / e.occ, green: e.greenSum / e.occ };
  })
  .sort((x, y) => y.occ - x.occ);

fs.writeFileSync(
  OUT,
  'a,b,songs,occurrences,avgBpm,avgGreen\n' +
    ranked.map(r => `${r.a},${r.b},${r.songs},${r.occ},${r.bpm.toFixed(2)},${r.green.toFixed(2)}`).join('\n') +
    '\n',
);

// The whole ranking is only a few hundred pairs, so the app carries all of it rather
// than a truncated top-N — every change a user can train has a real rank to show.
const generatedRows = ranked
  .map(r => `  ['${r.a}', '${r.b}', ${r.songs}, ${r.occ}],`)
  .join('\n');
fs.writeFileSync(GENERATED, `// GENERATED by scripts/transitionStats.ts — do not edit by hand.
// Run \`npm run stats:transitions\` to regenerate from public/catalog.sqlite.
//
// Every undirected base-triad chord change in the catalog, most frequent first, as
// [a, b, songs it appears in, total occurrences]. Index + 1 is the change's rank.
export const TRANSITION_FREQUENCY: readonly (readonly [string, string, number, number])[] = [
${generatedRows}
];

/** How many distinct chord changes the catalog contains — the denominator of a rank. */
export const TRANSITION_COUNT = TRANSITION_FREQUENCY.length;

export type TransitionFrequency = {
  rank: number;          // 1 = the most common change in the catalog
  songs: number;         // songs the change appears in
  occurrences: number;   // times it is played across all of them
};

const INDEX = new Map<string, TransitionFrequency>(
  TRANSITION_FREQUENCY.map(([a, b, songs, occurrences], i) =>
    [\`\${a}|\${b}\`, { rank: i + 1, songs, occurrences }]),
);

/** Frequency of an undirected base-triad pair, or null if the catalog never sees it. */
export function transitionFrequency(a: string, b: string): TransitionFrequency | null {
  const [x, y] = a <= b ? [a, b] : [b, a];
  return INDEX.get(\`\${x}|\${y}\`) ?? null;
}
`);

console.log(`Scanned ${scanned.toLocaleString()} songs with a tempo; ${ranked.length} distinct pairs.`);
const greens = ranked.slice(0, 120).map(r => r.green);
console.log(`Top-120 avg green spread: ${Math.min(...greens).toFixed(1)}–${Math.max(...greens).toFixed(1)}/min\n`);
console.log('rank  pair            songs      occurrences   avgBPM  avgGreen');
ranked.slice(0, 120).forEach((r, i) => {
  const pair = `${r.a} ↔ ${r.b}`;
  console.log(
    `${String(i + 1).padStart(4)}  ${pair.padEnd(14)} ${String(r.songs).padStart(8)} ` +
    `${String(r.occ).padStart(13)}  ${r.bpm.toFixed(1).padStart(6)}  ${r.green.toFixed(1).padStart(8)}`,
  );
});
console.log(`\nWrote ${OUT} and ${GENERATED}`);
